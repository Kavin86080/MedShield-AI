import re


class ResponseParser:

    def __init__(self):
        pass

    def clean_text(
        self,
        text: str
    ) -> str:

        if not text:
            return ""

        # Remove leading/trailing spaces
        text = text.strip()

        # Remove extra blank lines
        text = re.sub(r"\n{3,}", "\n\n", text)

        # Remove repeated spaces
        text = re.sub(r"[ ]{2,}", " ", text)

        return text

    def parse(
        self,
        response: str
    ) -> str:

        response = self.clean_text(response)

        return response